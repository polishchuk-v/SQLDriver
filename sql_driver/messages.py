# Переклад типових повідомлень SQLite. Порядок важливий: перше збігання.
_SQLITE_PATTERNS = [
    (r"no such table: (\S+)", "Таблицю «{0}» не знайдено."),
    (r"no such column: (\S+)", "Стовпець «{0}» не знайдено."),
    (r"table (\S+) already exists", "Таблиця «{0}» вже існує."),
    (r"index (\S+) already exists", "Індекс «{0}» вже існує."),
    (r"UNIQUE constraint failed: (.+)", "Значення має бути унікальним: {0}."),
    (r"NOT NULL constraint failed: (.+)", "Поле {0} не може бути порожнім."),
    (r"CHECK constraint failed: (.+)", "Значення не відповідає умові перевірки ({0})."),
    (r"FOREIGN KEY constraint failed",
     "Операцію відхилено, бо вона порушує зв'язки між записами (зовнішній ключ)."),
    (r'near "(.+?)": syntax error', "Синтаксична помилка поблизу «{0}»."),
    (r"incomplete input", "Запит не завершено. Перевірте дужки та лапки."),
    (r"table (\S+) has (\d+) columns but (\d+) values were supplied",
     "Таблиця «{0}» має {1} стовпців, а передано {2} значень."),
    (r"(\d+) values for (\d+) columns",
     "Кількість значень ({0}) не відповідає кількості стовпців ({1})."),
    (r"no such function: (\S+)", "Функцію «{0}» не знайдено."),
    (r"ambiguous column name: (\S+)", "Назва стовпця «{0}» неоднозначна."),
    (r"database is locked", "Базу даних заблоковано іншим процесом. Спробуйте пізніше."),
    (r"unable to open database file", "Не вдалося відкрити файл бази даних."),
    (r"file is not a database", "Обраний файл не є базою даних SQLite."),
    (r"readonly database", "Базу даних відкрито лише для читання."),
    (r"cannot (?:start|commit|rollback)", "Неможлива операція з транзакцією в поточному стані."),
]
_COMPILED = [(re.compile(p, re.IGNORECASE), text) for p, text in _SQLITE_PATTERNS]

SQLITE_GENERIC = "Під час роботи з базою даних сталася помилка."


def translate_sqlite_message(original: str) -> str:
    # Повертає українське повідомлення для англомовного тексту помилки SQLite
    for pattern, text in _COMPILED:
        match = pattern.search(original)
        if match:
            return text.format(*match.groups())
    return SQLITE_GENERIC
